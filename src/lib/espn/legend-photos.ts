/** NBA.com's photo of a legend ESPN has none of, or undefined. */
export const legendPhoto = (espnId: string): string | undefined =>
  LEGEND_PHOTOS[espnId] ? `https://cdn.nba.com/headshots/nba/latest/260x190/${LEGEND_PHOTOS[espnId]}.png` : undefined;

/** The headshot file of an athlete: ESPN's, or NBA.com's for a legend ESPN has none of (see `LEGEND_PHOTOS`). */
export const headshotUrl = (athleteId: string): string =>
  legendPhoto(athleteId) ?? `https://a.espncdn.com/i/headshots/nba/players/full/${athleteId}.png`;
