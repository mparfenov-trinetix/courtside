// Usage: node --experimental-strip-types scripts/build-franchise-eras.ts [outFile]
// Walks ESPN's season-scoped team records (core API, every season from 1980) and writes down where a team's identity (name, tri-code,
// logo, colors) changed: the Sonics to Oklahoma City, the Nets to Brooklyn... The output is the data file `src/lib/espn/franchise-eras.ts`.
const CORE = 'https://sports.core.api.espn.com/v2/sports/basketball/leagues/nba';
const FIRST = 1980;
const now = new Date();
const LAST = now.getFullYear() + (now.getMonth() >= 9 ? 1 : 0);

async function getJson(url: string, tries = 3): Promise<any> {
  for (let i = 0; i < tries; i++) {
    try {
      const res = await fetch(url.replace('http://', 'https://'));
      if (res.status === 404) return null;
      if (res.ok) return await res.json();
    } catch {}
    await new Promise((r) => setTimeout(r, 400 * (i + 1)));
  }
  return null;
}

async function pool<T, R>(items: T[], size: number, fn: (item: T) => Promise<R>): Promise<R[]> {
  const out: R[] = new Array(items.length);
  let next = 0;
  await Promise.all(
    Array.from({ length: size }, async () => {
      while (next < items.length) {
        const i = next++;
        out[i] = await fn(items[i]);
      }
    }),
  );
  return out;
}

type Era = { from: number; name: string; location: string; nickname: string; abbr: string; logo: string; logoDark: string; color: string; alt: string };
const logoOf = (t: any, rel: string) => (t.logos ?? []).find((l: any) => l.rel?.length === 2 && l.rel.includes(rel) && l.rel.includes(rel === 'dark' ? 'full' : 'default'))?.href ?? '';

const seasons = Array.from({ length: LAST - FIRST + 1 }, (_, i) => FIRST + i);
const rows = await pool(seasons, 4, async (season) => {
  const list = await getJson(`${CORE}/seasons/${season}/teams?limit=60`);
  const refs: string[] = (list?.items ?? []).map((i: any) => i.$ref);
  const teams = await pool(refs, 6, (ref) => getJson(ref));
  return { season, teams: teams.filter(Boolean) };
});

/** ESPN's names, cleaned: stray line breaks, and "NO/Oklahoma City Hornets" (the two seasons the Hornets played part of their games there) spelled out. */
const clean = (name: string) => name.replace(/\s+/g, ' ').trim().replace(/^NO\//, 'New Orleans/');
/** "LA" and "Los Angeles" are one identity (ESPN switches the Clippers' to "LA" in 2002, years before the team did). */
const identity = (name: string) => name.replace(/^Los Angeles /, 'LA ');

const byId = new Map<string, Era[]>();
for (const { season, teams } of rows) {
  for (const t of teams) {
    const era: Era = {
      from: season,
      name: clean(t.displayName),
      location: clean(t.location ?? ''),
      nickname: clean(t.name ?? ''),
      abbr: t.abbreviation ?? '',
      logo: logoOf(t, 'default'),
      logoDark: logoOf(t, 'dark'),
      color: (t.color ?? '').toLowerCase(),
      alt: (t.alternateColor ?? '').toLowerCase(),
    };
    const eras = byId.get(String(t.id)) ?? [];
    const last = eras[eras.length - 1];
    // A new era starts when the name changes (a new logo or color alone is ESPN re-skinning, not a new identity). Before 1985 ESPN has no
    // tri-codes: they are filled in from the first season that has one.
    if (!last || identity(last.name) !== identity(era.name)) eras.push(era);
    else if (!last.abbr && era.abbr) last.abbr = era.abbr;
    byId.set(String(t.id), eras);
  }
}

const out = process.argv[2] ?? 'franchise-eras.generated.ts';
const lines: string[] = [];
const ids = [...byId.keys()].sort((a, b) => Number(a) - Number(b));
for (const id of ids) {
  const eras = byId.get(id)!;
  const seen = rows.filter((r) => r.teams.some((t: any) => String(t.id) === id)).map((r) => r.season);
  lines.push(`  '${id}': { first: ${seen[0]}, last: ${seen[seen.length - 1]}, eras: ${JSON.stringify(eras)} },`);
}
const body = `// Generated by scripts/build-franchise-eras.ts from ESPN's season-scoped team records (core API, ${FIRST} to ${LAST}). Do not edit by hand.\n// \`first\` and \`last\` are the seasons ESPN lists the team in (a season is the year it ends in: 2009 is 2008-09), each era is\n// where the name or tri-code changed.\nexport const FRANCHISE_ERAS: Record<string, { first: number; last: number; eras: { from: number; name: string; location: string; nickname: string; abbr: string; logo: string; logoDark: string; color: string; alt: string }[] }> = {\n${lines.join('\n')}\n};\n`;
const { writeFileSync } = await import('node:fs');
writeFileSync(out, body);
console.log(`wrote ${out}: ${ids.length} team ids, ${[...byId.values()].filter((e) => e.length > 1).length} with more than one identity`);
